const assert=require('node:assert/strict');
const fs=require('node:fs');const vm=require('node:vm');
const path=require('node:path');const root=path.resolve(__dirname,'..');
const engine=require('../js/ashen-060-bonuses.js');
const adapter=require('../js/ashen-060-equipment-preview.js');
const socket=require('../js/ashen-236-socket-lab.js');
const context={window:{}};vm.runInNewContext(fs.readFileSync(path.join(root,'data/ashen-060-katalog.js'),'utf8'),context);
const catalog=context.window.Ashen060Catalog;
const item={uid:'only-item',id:'m9',socketCapacity:2,socketedArtifacts:[]};
const choices=adapter.artifactChoices(catalog,'right',engine);
assert.ok(choices.length>1,'brak artefaktow w katalogu dla broni');
let one=socket.modify(item,choices[0].name,'install','right',catalog,engine,adapter);
assert.equal(item.socketedArtifacts.length,0,'funkcja musi byc niemutujaca');
assert.equal(one.socketedArtifacts.length,1);
let second=choices.find(c=>c.family!==choices[0].family);
assert.ok(second,'brak dwoch rodzin artefaktow do testu');
let two=socket.modify(one,second.name,'install','right',catalog,engine,adapter);
assert.equal(two.socketedArtifacts.length,2);
assert.throws(()=>socket.modify(two,choices[0].name,'install','right',catalog,engine,adapter),/zajęte/);
assert.throws(()=>socket.modify(one,choices[0].name,'install','right',catalog,engine,adapter),/zdublowany|rodziny/);
assert.throws(()=>socket.modify({...item,socketCapacity:0},choices[0].name,'install','right',catalog,engine,adapter),/gniazd/);
assert.throws(()=>socket.modify(item,'nieznany artefakt','install','right',catalog,engine,adapter),/pasuje/);
assert.throws(()=>socket.modify(item,choices[0].name,'install','nonsense',catalog,engine,adapter),/slot/);
const removed=socket.modify(two,0,'remove','right',catalog,engine,adapter);
assert.equal(removed.socketedArtifacts.length,1);assert.equal(removed.socketedArtifacts[0],second.name);
const roundtrip=JSON.parse(JSON.stringify(removed));assert.equal(roundtrip.socketedArtifacts[0],second.name);
assert.throws(()=>socket.modify(removed,3,'remove','right',catalog,engine,adapter),/znaleziono/);
console.log('PASS ASHEN 236: test instalacji, usuwania, limitu, rodzin, zapisu JSON');
