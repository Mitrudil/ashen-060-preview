'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const ctx={window:{},Date,Math};
vm.runInNewContext(fs.readFileSync(path.join(root,'js/ashen-zone-239.js'),'utf8'),ctx);
const zone=ctx.window.AshenZone239;
assert.equal(zone.scenes.length,5);
assert(zone.scenes.every(s=>s.choices.length===3&&s.text.length===2));
assert(zone.html(null).includes('Rozpocznij historię'));
let session=zone.initial();
const attrs={per:16,dex:18,end:15,int:12};
for(let scene=0;scene<4;scene++){
 let result=zone.pick(session,scene%3,attrs,()=>.05);
 assert.equal(result.scene,scene);
 assert.equal(session.scene,scene+1);
 assert.equal(session.history.length,scene+1);
}
assert.equal(session.status,'combat_pending');
assert(zone.html(session).includes('Obowiązkowe starcie'));
assert.throws(()=>zone.pick(session,0,attrs));
let restored=JSON.parse(JSON.stringify(session));
assert.equal(restored.history.length,4);
zone.setCombat(restored,{won:false,enemy:'Nasłuchujący',lines:['Runda 1']});
assert.equal(restored.status,'playing');
assert.throws(()=>zone.setCombat(restored,{won:true}));
zone.pick(restored,0,attrs,()=>.9);
assert.equal(restored.status,'finished');
assert.equal(restored.history.length,5);
assert(zone.html(restored).includes('HISTORIA ZAKOŃCZONA'));
assert.throws(()=>zone.pick(restored,2,attrs));
const game=fs.readFileSync(path.join(root,'js/game.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(game.includes("['zone','◈ Strefa Anomalii']"));
assert(game.includes("zone:()=>window.AshenZone239?.html(zone239Read())"));
assert(game.includes('const artifactFind=null;'));
assert(!game.includes('rollExpeditionArtifact(loc)'));
assert(html.includes('ashen-zone-239.js?v=243'));
assert(html.indexOf('ashen-zone-239.js?v=243')<html.indexOf('game.js?v=243'));
console.log('PASS ASHEN 239: 5 scen, 15 opcji, save/reload, jeden raport walki, bez duplikacji losowania, artefakty poza zwykłymi wyprawami');
